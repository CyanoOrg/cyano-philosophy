EVO_KEY = lambda it: (0,) if it["t"].startswith(("篇目单","Table of")) else ((99,) if it["t"].startswith(("附录","Appendix")) else ((int(it["t"].split()[0]),) if it["t"].split()[0].isdigit() else (50,)))

def scan(group, d, lang, skip_readme=False):
    items = []
    for fn in sorted(os.listdir(d)):
        if not fn.endswith(".md") or (skip_readme and fn == "README.md"):
            continue
        p = f"{d}/{fn}"
        items.append({"path": p, "t": OVERRIDES[lang].get(p) or h1(p)})
    if not items: return None
    if "evolution" in d: items.sort(key=EVO_KEY)
    return {"g": group, "items": items}

def build(lang):
    sub = "zh-CN" if lang == "zh" else "en"
    g = {
     "zh": ["正典 · axioms","判据 · criteria","协议 · protocols","术语 · wiki","演化档案 · evolution"],
     "en": ["Axioms","Criteria","Protocols","Wiki","Evolution Archive"],
    }[lang]
    ov = "总览" if lang == "zh" else "Overview"
    rt = [("README.zh-CN.md","体系总览"),("CHARTER.zh-CN.md","修订治理条约"),("DECISIONS.md","治理决策账本"),("MAPPING.md","命题映射台账")] if lang=="zh" else [("README.md","System overview · diagram"),("CHARTER.en.md","Revision governance charter")]
    groups = [{"g": ov, "items": [{"path": p, "t": t} for p,t in rt]},
              scan(g[0], f"axioms/{sub}", lang, skip_readme=True),
              scan(g[1], f"criteria/{sub}", lang),
              scan(g[2], f"protocols/{sub}", lang, skip_readme=True),
              scan(g[3], f"wiki/{sub}", lang, skip_readme=True),
              scan(g[4], f"evolution/{sub}", lang)]
    return {"$comment": "Auto-generated by tools/gen_manifest.py v3 (bilingual). 手改无效：--check 会抓",
            "language": "zh-CN" if lang=="zh" else "en",
            "groups": [x for x in groups if x]}

outs = {"manifest.json": build("zh"), "manifest.en.json": build("en")}
if "--check" in sys.argv:
    ok = True
    for fn, m in outs.items():
        disk = open(fn).read()
        new = json.dumps(m, ensure_ascii=False, indent=2) + "\n"
        if disk != new:
            print(f"DRIFT: {fn}"); ok = False
    sys.exit(0 if ok else 1)
for fn, m in outs.items():
    open(fn, "w").write(json.dumps(m, ensure_ascii=False, indent=2) + "\n")
    print(f"{fn}: {sum(len(g['items']) for g in m['groups'])} items")
